/**
 * Shell completion script generation for novaos-cli.
 *
 * Commander has no built-in completion generator (as of the version pinned
 * here), so this hand-rolls a bash script from the command tree instead of
 * wiring up a library feature.
 */

import type { Command } from "commander";

export const SUPPORTED_SHELLS = ["bash"] as const;
export type CompletionShell = (typeof SUPPORTED_SHELLS)[number];

export function isSupportedShell(shell: string): shell is CompletionShell {
  return (SUPPORTED_SHELLS as readonly string[]).includes(shell);
}

export interface CompletionCommandSpec {
  name: string;
  subcommands: string[];
}

/** Walks a Commander program's top-level commands and their direct subcommands. */
export function buildCompletionSpec(program: Command): CompletionCommandSpec[] {
  return program.commands.map((cmd) => ({
    name: cmd.name(),
    subcommands: cmd.commands.map((sub) => sub.name()),
  }));
}

export interface CompletionGlobalOptions {
  /** Flags that consume a following argument (e.g. "--env <name>"), so completion must skip both tokens. */
  valueFlags: string[];
  /** Flags with no argument (e.g. "--debug"). */
  boolFlags: string[];
}

/**
 * Global flags precede the subcommand in real invocations (e.g.
 * "novaos-cli --env staging auth login"), so completion has to skip past
 * them — and their values, for the ones that take one — to find the actual
 * command word instead of assuming it always sits at a fixed index.
 */
export function buildGlobalOptionsSpec(program: Command): CompletionGlobalOptions {
  const valueFlags: string[] = [];
  const boolFlags: string[] = ["-h", "--help"];
  for (const option of program.options) {
    const flags = [option.short, option.long].filter((f): f is string => Boolean(f));
    if (option.required || option.optional) {
      valueFlags.push(...flags);
    } else {
      boolFlags.push(...flags);
    }
  }
  return { valueFlags, boolFlags };
}

export function generateBashCompletion(
  binName: string,
  commands: CompletionCommandSpec[],
  globalOptions: CompletionGlobalOptions
): string {
  const fnName = `_${binName.replace(/-/g, "_")}_completions`;
  const topLevel = commands.map((c) => c.name).join(" ");
  const subcaseLines = commands
    .filter((c) => c.subcommands.length > 0)
    .map((c) => `    ${c.name}) opts="${c.subcommands.join(" ")}" ;;`)
    .join("\n");
  const valueFlags = globalOptions.valueFlags.join(" ");
  const boolFlags = globalOptions.boolFlags.join(" ");

  return `# bash completion for ${binName}
# Generated by "${binName} completion bash" — source this file, or copy it to
# your bash completion directory (e.g. /usr/local/etc/bash_completion.d/).
# Depends only on bash's own compgen/complete builtins — no bash-completion
# package required.
${fnName}() {
  local cur="\${COMP_WORDS[COMP_CWORD]}"
  local top_level="${topLevel}"
  local global_value_flags="${valueFlags}"
  local global_bool_flags="${boolFlags}"

  # Skip past leading global flags (and their values) to find the command word,
  # since global flags like --env/--debug can precede the subcommand. A flag
  # given as "--flag=value" consumes one token; "--flag value" consumes two —
  # unless the value itself is the token being completed, in which case there
  # is no command word yet and nothing sensible to suggest.
  local i=1
  local cmd_index=-1
  while [ "\${i}" -lt "\${COMP_CWORD}" ]; do
    local word="\${COMP_WORDS[$i]}"
    local flag_name="\${word%%=*}"
    case " \${global_value_flags} " in
      *" \${flag_name} "*)
        if [[ "\${word}" == *=* ]]; then
          i=$((i + 1))
        elif [ $((i + 1)) -eq "\${COMP_CWORD}" ]; then
          cmd_index=-2
          break
        else
          i=$((i + 2))
        fi
        continue
        ;;
    esac
    case " \${global_bool_flags} " in
      *" \${flag_name} "*) i=$((i + 1)); continue ;;
    esac
    cmd_index=$i
    break
  done

  if [ "\${cmd_index}" -eq -2 ]; then
    # We don't know this flag's valid values, but suppress "-o default"'s
    # filename fallback for this one completion — a bare path guess is
    # actively misleading for a flag like --retry-mode or --client-id.
    COMPREPLY=()
    compopt +o default 2>/dev/null || true
    return
  fi

  if [ "\${cmd_index}" -eq -1 ]; then
    if [[ "\${cur}" == -* ]]; then
      COMPREPLY=( $(compgen -W "\${global_value_flags} \${global_bool_flags}" -- "\${cur}") )
    else
      COMPREPLY=( $(compgen -W "\${top_level}" -- "\${cur}") )
    fi
    return
  fi

  if [ "\${COMP_CWORD}" -eq "\${cmd_index}" ]; then
    COMPREPLY=( $(compgen -W "\${top_level}" -- "\${cur}") )
    return
  fi

  if [ "\${COMP_CWORD}" -ne "$((cmd_index + 1))" ]; then
    # Past the subcommand position (e.g. a path argument) — leave COMPREPLY
    # empty so "-o default" falls back to readline's filename completion
    # instead of re-offering sibling subcommand names forever.
    COMPREPLY=()
    return
  fi

  local cmd="\${COMP_WORDS[$cmd_index]}"
  local opts=""
  case "\${cmd}" in
${subcaseLines}
    *) opts="" ;;
  esac

  COMPREPLY=( $(compgen -W "\${opts}" -- "\${cur}") )
}
complete -o bashdefault -o default -F ${fnName} ${binName}
`;
}

export function generateCompletionScript(
  binName: string,
  commands: CompletionCommandSpec[],
  globalOptions: CompletionGlobalOptions
): string {
  return generateBashCompletion(binName, commands, globalOptions);
}
