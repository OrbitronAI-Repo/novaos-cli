// ---------------------------------------------------------------------------
// SSRF validation (R-SSRF, connector-manifest-standards.mdc)
// ---------------------------------------------------------------------------

/**
 * Forbidden values for `ssrf.allowed_domains` in connector.json.
 *
 * Patterns are applied to the domain string itself (not to a URL), so
 * anchored regexes are appropriate here — there is no URL substring-matching
 * ambiguity (js/incomplete-url-substring-sanitization).
 *
 * The cloud metadata endpoint is treated as an exact-match constant to
 * prevent any possible regex confusion with similar-looking addresses.
 */
const CLOUD_METADATA_ENDPOINT = "169.254.169.254" as const;

/**
 * DNS-name aliases clouds expose for the same metadata service as
 * `CLOUD_METADATA_ENDPOINT`. Blocking only the IP literal misses these —
 * a hostname in `ssrf.allowed_domains` is never resolved before this check
 * runs, so an alias like GCP's `metadata.google.internal` sails through an
 * IP-only blocklist untouched while still reaching the same sensitive
 * endpoint. Matched case-insensitively, like the other hostname alias
 * (`localhost`) below.
 */
const CLOUD_METADATA_HOSTNAME_ALIASES: ReadonlySet<string> = new Set(
  ["metadata.google.internal", "metadata.internal"].map((h) => h.toLowerCase())
);

const FORBIDDEN_SSRF_PATTERNS: ReadonlyArray<RegExp> = [
  /^\*$/, // bare wildcard
  /^10\.\d{1,3}\.\d{1,3}\.\d{1,3}$/, // RFC1918 10.x.x.x
  /^192\.168\.\d{1,3}\.\d{1,3}$/, // RFC1918 192.168.x.x
  /^172\.(1[6-9]|2\d|3[01])\.\d{1,3}\.\d{1,3}$/, // RFC1918 172.16–31.x.x
  /^10\.0\.0\.0\/8$/, // RFC1918 CIDR notation
  /^192\.168\.0\.0\/16$/,
  /^172\.(1[6-9]|2\d|3[01])\.0\.0\/12$/,
  /^0\.0\.0\.0$/, // unspecified address
  /^127\.\d{1,3}\.\d{1,3}\.\d{1,3}$/, // loopback
  /^::1$/, // IPv6 loopback
  /^localhost$/i, // hostname loopback alias
  /^localhost\.localdomain$/i, // alternate loopback alias
];

/**
 * Validate every entry in `ssrf.allowed_domains`.
 *
 * Throws a descriptive error on the first forbidden value found.
 * The connector manifest must be rejected before any files are written.
 */
export function validateSsrfAllowedDomains(domains: string[]): void {
  for (const domain of domains) {
    // Exact-match the cloud metadata endpoint (no regex needed, no substring risk)
    if (domain === CLOUD_METADATA_ENDPOINT) {
      throw new Error(
        `Forbidden ssrf.allowed_domains value: "${domain}" — cloud metadata endpoint is disallowed (R-SSRF)`
      );
    }
    if (CLOUD_METADATA_HOSTNAME_ALIASES.has(domain.toLowerCase())) {
      throw new Error(
        `Forbidden ssrf.allowed_domains value: "${domain}" — cloud metadata endpoint alias is disallowed (R-SSRF)`
      );
    }
    for (const pattern of FORBIDDEN_SSRF_PATTERNS) {
      if (pattern.test(domain)) {
        throw new Error(
          `Forbidden ssrf.allowed_domains value: "${domain}" — matches disallowed pattern ${pattern} (R-SSRF)`
        );
      }
    }
  }
}

