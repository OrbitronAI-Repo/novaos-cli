function stderr(msg: string): void {
  process.stderr.write(msg);
}

function ensureDocker(): void {
  try {
    execSync("docker info", { stdio: "ignore" });
  } catch {
    throw new Error(
      "Docker is required for novaos-cli mcp publish. Start Docker Desktop or the Docker daemon.\n" +
        "If Docker is installed but not in PATH, set the DOCKER_HOST environment variable."
    );
  }
}

export function resolveDockerfile(manifestPath: string, dockerfileOverride?: string): string {
  const manifestDir = path.dirname(path.resolve(manifestPath));
  const dockerfile = dockerfileOverride ?? path.join(manifestDir, "Dockerfile");
  if (!existsSync(dockerfile)) {
    throw new Error(
      `Dockerfile not found at ${dockerfile}. Provide --dockerfile <path> if using a non-standard layout.`
    );
  }
  return dockerfile;
}

function dockerBuild(
  imageRef: string,
  dockerfile: string,
  contextDir: string,
  platform: string
): Promise<void> {
  return new Promise((resolve, reject) => {
    const proc = spawn(
      "docker",
      [
        "buildx",
        "build",
        "--platform",
        platform,
        "--load",
        "-t",
        imageRef,
        "-f",
        dockerfile,
        contextDir,
      ],
      { stdio: ["ignore", "pipe", "inherit"] }
    );

    proc.stdout?.on("data", (data: Buffer) => {
      process.stderr.write(data);
    });

    proc.on("close", (code) => {
      if (code !== 0) reject(new Error(`Docker build failed with exit code ${code}`));
      else resolve();
    });

    proc.on("error", (err) => {
      reject(new Error(`Docker build error: ${err.message}`));
    });
  });
}

function dockerPush(imageRef: string, env?: NodeJS.ProcessEnv): Promise<void> {
  return new Promise((resolve, reject) => {
    const proc = spawn("docker", ["push", imageRef], {
      stdio: ["ignore", "pipe", "inherit"],
      ...(env ? { env } : {}),
    });

    proc.stdout?.on("data", (data: Buffer) => {
      process.stderr.write(data);
    });

    proc.on("close", (code) => {
      if (code !== 0) reject(new Error(`Docker push failed with exit code ${code}`));
      else resolve();
    });

    proc.on("error", (err) => {
      reject(new Error(`Docker push error: ${err.message}`));
    });
  });
}

/**
 * Pushes an image using an isolated Docker config that holds only the provided
 * oauth2accesstoken credential for the target registry.
 *
 * This bypasses any system credential helpers (e.g. gcloud auth docker-helper)
 * that may be configured in the user's ~/.docker/config.json. Those helpers
 * take priority over stored `auths` entries even after `docker login`, so the
 * only reliable way to use a server-vended token is to supply a clean config
 * via the DOCKER_CONFIG env var — the same approach used by crane, ko, and skopeo.
 */
function dockerPushWithToken(imageRef: string, registryHost: string, token: string): Promise<void> {
  const tmpDir = mkdtempSync(path.join(tmpdir(), "novaos-docker-"));
  const authValue = Buffer.from(`oauth2accesstoken:${token}`).toString("base64");
  const dockerConfig = { auths: { [registryHost]: { auth: authValue } } };
  writeFileSync(path.join(tmpDir, "config.json"), JSON.stringify(dockerConfig));

  return dockerPush(imageRef, envForIsolatedDockerConfig(tmpDir)).finally(() => {
    rmSync(tmpDir, { recursive: true, force: true });
  });
}

/** Parse KEY=VALUE lines from env file content. Skips comments and blanks. */
export function parseEnvLines(content: string): Record<string, string> {
  const result: Record<string, string> = {};
  for (const line of content.split("\n")) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith("#")) continue;
    const eqIdx = trimmed.indexOf("=");
    if (eqIdx === -1) continue;
    const key = trimmed.substring(0, eqIdx).trim();
    const value = trimmed.substring(eqIdx + 1).trim();
    if (key) result[key] = value;
  }
  return result;
}

function parseEnvFile(envPath: string): Record<string, string> {
  return parseEnvLines(readFileSync(envPath, "utf-8"));
}

export interface SecretValidationResult {
  secrets: Record<string, string>;
  errors: string[];
}

/** Validate declared secret keys against parsed env data. Pure function. */
export function validateDeclaredSecrets(
  declaredEnv: string[],
  envData: Record<string, string>
): SecretValidationResult {
  const errors: string[] = [];
  const secrets: Record<string, string> = {};

  for (const key of declaredEnv) {
    if (!(key in envData)) {
      errors.push(`Missing key "${key}" in .env (declared in secrets.env)`);
    } else if (envData[key] === "") {
      errors.push(`Empty value for "${key}" in .env`);
    } else {
      secrets[key] = envData[key];
    }
  }

  return { secrets, errors };
}

function loadAndValidateSecrets(
  manifest: McpManifestV2,
  manifestPath: string,
  json?: boolean
): Record<string, string> | undefined {
  const declaredEnv = manifest.secrets?.env;
  if (!declaredEnv || declaredEnv.length === 0) return undefined;

  const manifestDir = path.dirname(path.resolve(manifestPath));
  const envPath = path.join(manifestDir, ".env");

  try {
    execSync(`git ls-files --error-unmatch "${envPath}"`, { stdio: "ignore", cwd: manifestDir });
    throw new Error(
      `.env file at "${envPath}" is tracked by git. This file contains secrets.\n` +
        "Add .env to .gitignore and run: git rm --cached .env"
    );
  } catch (err) {
    if (err instanceof Error && err.message.includes("tracked by git")) throw err;
  }

  if (!existsSync(envPath)) {
    throw new Error(
      `Manifest declares secrets.env but .env file not found at ${envPath}.\n` +
        `Create a .env file with the required keys: ${declaredEnv.join(", ")}`
    );
  }

  const envData = parseEnvFile(envPath);
  const { secrets, errors } = validateDeclaredSecrets(declaredEnv, envData);

  if (errors.length > 0) {
    throw new Error(`Secret validation failed:\n${errors.map((e) => `  ${e}`).join("\n")}`);
  }

  const extraKeys = Object.keys(envData).filter((k) => !declaredEnv.includes(k));
  if (extraKeys.length > 0 && !json) {
    stderr(`  Warning: .env contains keys not in secrets.env (ignored): ${extraKeys.join(", ")}\n`);
  }

  return secrets;
}

export interface McpPublishDeps {
  ensureDocker?: () => void;
  resolveDockerfile?: (manifestPath: string, dockerfileOverride?: string) => string;
  dockerBuild?: (
    imageRef: string,
    dockerfile: string,
    contextDir: string,
    platform: string
  ) => Promise<void>;
  dockerPush?: (imageRef: string, env?: NodeJS.ProcessEnv) => Promise<void>;
  dockerPushWithToken?: (imageRef: string, registryHost: string, token: string) => Promise<void>;
  readManifestFile?: (filePath: string) => string;
  loadAndValidateSecrets?: (
    manifest: McpManifestV2,
    manifestPath: string,
    json?: boolean
  ) => Record<string, string> | undefined;
  stderr?: (msg: string) => void;
  stdout?: (msg: string) => void;
}

export async function mcpPublish(
  client: GalaxyHttpClient,
  opts: McpPublishOptions,
  deps?: McpPublishDeps
): Promise<void> {
  const _ensureDocker = deps?.ensureDocker ?? ensureDocker;
  const _resolveDockerfile = deps?.resolveDockerfile ?? resolveDockerfile;
  const _dockerBuild = deps?.dockerBuild ?? dockerBuild;
  const _dockerPush = deps?.dockerPush ?? dockerPush;
  const _dockerPushWithToken = deps?.dockerPushWithToken ?? dockerPushWithToken;
  const _readManifestFile =
    deps?.readManifestFile ?? ((p: string) => readFileSync(path.resolve(p), "utf-8"));
  const _loadAndValidateSecrets = deps?.loadAndValidateSecrets ?? loadAndValidateSecrets;
  const _stderr = deps?.stderr ?? stderr;
  const _stdout =
    deps?.stdout ??
    ((msg: string) => {
      process.stdout.write(msg);
    });

  const {
    manifestPath,
    imageUri,
    dockerfile: dockerfileOverride,
    context: contextOverride,
    dryRun,
    json,
    platform: platformOverride,
    envName,
  } = opts;

  const targetPlatform = resolveTargetPlatform(platformOverride, envName);
  const useImageUri = !!imageUri;

  if (!useImageUri) {
    if (!json) _stderr("Checking Docker... ");
    _ensureDocker();
    if (!json) _stderr("ok\n");
  }

  if (!json) _stderr("Validating manifest... ");
  let raw: unknown;
  try {
    const content = _readManifestFile(manifestPath);
    raw = JSON.parse(content);
  } catch (error) {
    throw new Error(`Failed to read manifest at "${manifestPath}": ${stringifyError(error)}`);
  }

  const validation = validateMcpManifest(raw);
  if (!validation.valid) {
    const details = validation.errors?.map((e) => `  ${e.path}: ${e.message}`).join("\n") ?? "";
    throw new Error(`Manifest validation failed:\n${details}`);
  }

  const manifest = validation.manifest!;

  if (!semver.valid(manifest.version)) {
    throw new Error(`Invalid version "${manifest.version}". Must be valid SemVer (e.g., 1.0.0).`);
  }

  if (!json)
    _stderr(`ok (${manifest.name} v${manifest.version}, publisher: ${manifest.publisher})\n`);

  let secrets: Record<string, string> | undefined;
  if (manifest.secrets?.env && manifest.secrets.env.length > 0) {
    if (!json) _stderr("Validating secrets... ");
    secrets = _loadAndValidateSecrets(manifest, manifestPath, json);
    if (!json) _stderr(`ok (${manifest.secrets.env.length} secret(s))\n`);
  }

  if (useImageUri) {
    if (!json) _stderr("Using pre-built image, skipping build/push...\n");
    await finalizePublish(client, raw, imageUri, manifest, json, secrets);
    return;
  }

  const dockerfile = _resolveDockerfile(manifestPath, dockerfileOverride);
  const contextDir = contextOverride
    ? path.resolve(contextOverride)
    : path.dirname(path.resolve(manifestPath));

  if (!json) _stderr("Requesting publish authorization... ");

  const authResponse = await client.request<PublishAuthResponse>("/api/v1/mcp-ops/publish/auth", {
    method: "POST",
    body: { manifest },
  });

  if (!authResponse.ok) {
    throw new Error(
      withRequestId(
        `Publish authorization failed (HTTP ${authResponse.status}): ${extractErrorDetail(authResponse.data)}`,
        authResponse
      )
    );
  }

  const authData = authResponse.data.data;
  if (!authData) {
    throw new Error("MCP publish auth: received empty response from server");
  }
  const latestInfo = authData.latest_version
    ? `, latest: ${authData.latest_version}`
    : ", first version";
  if (!json) _stderr(`ok (new version${latestInfo})\n`);

  if (dryRun) {
    if (!json) {
      _stderr("\n--dry-run: Skipping build, push, and finalize.\n");
      _stderr(`  Would build: ${dockerfile}\n`);
      _stderr(`  Would push to: ${authData.image_ref}\n`);
      _stderr(`  Platform: ${targetPlatform}\n`);
      if (secrets) {
        _stderr(`  Would send ${Object.keys(secrets).length} secret(s)\n`);
      }
    } else {
      _stdout(
        JSON.stringify(
          {
            dry_run: true,
            tool_name: manifest.name,
            version: manifest.version,
            image_ref: authData.image_ref,
            latest_version: authData.latest_version,
            secrets_count: secrets ? Object.keys(secrets).length : 0,
          },
          null,
          2
        ) + "\n"
      );
    }
    return;
  }

  if (!json) _stderr(`Building image (platform: ${targetPlatform})...\n`);
  await _dockerBuild(authData.image_ref, dockerfile, contextDir, targetPlatform);
  if (!json) _stderr("Image built.\n");

  if (!json) _stderr(`Pushing image to ${authData.image_ref}...\n`);
  if (authData.registry_auth_required && authData.registry_token) {
    const registryHost = authData.image_ref.split("/")[0];
    await _dockerPushWithToken(authData.image_ref, registryHost, authData.registry_token);
  } else {
    await _dockerPush(authData.image_ref);
  }
  if (!json) _stderr("Image pushed.\n");

  await finalizePublish(client, raw, authData.image_ref, manifest, json, secrets);
}

export async function finalizePublish(
  client: GalaxyHttpClient,
  rawManifest: unknown,
  imageRef: string,
  manifest: McpManifestV2,
  json?: boolean,
  secrets?: Record<string, string>
): Promise<void> {
  if (!json) stderr("Registering with review pipeline... ");

  const idempotencyKey = `${manifest.publisher}:${manifest.name}:${manifest.version}`;

  // eslint-disable-next-line @typescript-eslint/no-explicit-any
  const body: Record<string, any> = {
    manifest: rawManifest,
    image_uri: imageRef,
  };
  if (secrets && Object.keys(secrets).length > 0) {
    body.secrets = secrets;
  }

  const response = await client.request<McpOpsPublishResponse>("/api/v1/mcp-ops/tools/publish", {
    method: "POST",
    body,
    headers: {
      "X-Idempotency-Key": idempotencyKey,
    },
  });

  if (!response.ok) {
    throw new Error(
      withRequestId(
        `Publish finalization failed (HTTP ${response.status}): ${extractErrorDetail(response.data)}`,
        response
      )
    );
  }

  const result = response.data.data;
  if (!result) {
    throw new Error("MCP publish finalize: received empty response from server");
  }
  if (!json) stderr("ok\n");

  if (json) {
    process.stdout.write(
      JSON.stringify({ tool_name: manifest.name, version: manifest.version, ...result }, null, 2) +
        "\n"
    );
  } else {
    stderr(`\nPublished! Version ID: ${result.versionId}\n`);
    stderr(`  Status: ${result.status}\n`);
    stderr(`  Image:  ${imageRef}\n`);
  }
}
