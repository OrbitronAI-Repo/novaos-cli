// ---- Connector detection ----

const CONNECTOR_CATEGORY = "connector";
const CONNECTOR_TOOL_PREFIX = "novaos.connector.";
const VALID_SOURCE_TYPES = [
  "orbis",
  "lexisnexis",
  "refinitiv",
  "rest",
  "database",
  "graphql",
  "sql",
  "postman",
] as const;

function isConnectorManifest(categories: string[] | undefined): boolean {
  return Array.isArray(categories) && categories.includes(CONNECTOR_CATEGORY);
}

// ---- Validation ----

export interface McpManifestValidationResult {
  valid: boolean;
  manifest?: McpManifestV2;
  errors?: Array<{ path: string; message: string }>;
}

function validateConnectorRules(manifest: McpManifestV2): Array<{ path: string; message: string }> {
  const errors: Array<{ path: string; message: string }> = [];
  const categories = manifest.categories ?? [];

  if (categories.length < 2) {
    errors.push({
      path: "categories",
      message:
        'Connector manifests must declare categories: ["connector", "<source-type>"]. Missing source-type category.',
    });
  }

  const sourceType = categories.find((c) => c !== CONNECTOR_CATEGORY);
  if (
    sourceType &&
    !VALID_SOURCE_TYPES.includes(sourceType as (typeof VALID_SOURCE_TYPES)[number])
  ) {
    errors.push({
      path: "categories",
      message: `Unknown connector source type "${sourceType}". Valid types: ${VALID_SOURCE_TYPES.join(", ")}`,
    });
  }

  for (const tool of manifest.tools) {
    if (!tool.name.startsWith(CONNECTOR_TOOL_PREFIX)) {
      errors.push({
        path: `tools.${tool.name}`,
        message: `Connector tool names must follow "novaos.connector.<source>.<operation>" pattern. Got: "${tool.name}"`,
      });
    }
  }

  if (!manifest.health_check) {
    errors.push({
      path: "health_check",
      message:
        "Connector manifests must declare a health_check (external dependency probing required).",
    });
  }

  return errors;
}

export function validateMcpManifest(raw: unknown): McpManifestValidationResult {
  if (typeof raw !== "object" || raw === null) {
    return {
      valid: false,
      errors: [{ path: "", message: "Manifest must be a JSON object" }],
    };
  }

  const result = McpManifestV2Schema.safeParse(raw);
  if (!result.success) {
    return {
      valid: false,
      errors: result.error.issues.map((issue) => ({
        path: issue.path.join("."),
        message: issue.message,
      })),
    };
  }

  const errors: Array<{ path: string; message: string }> = [];

  const toolNames = result.data.tools.map((t) => t.name);
  const duplicates = toolNames.filter((name, i) => toolNames.indexOf(name) !== i);
  if (duplicates.length > 0) {
    errors.push({
      path: "tools",
      message: `Duplicate tool names: ${[...new Set(duplicates)].join(", ")}`,
    });
  }

  if (isConnectorManifest(result.data.categories)) {
    errors.push(...validateConnectorRules(result.data));
  }

  if (errors.length > 0) {
    return { valid: false, errors };
  }

  return { valid: true, manifest: result.data };
}

