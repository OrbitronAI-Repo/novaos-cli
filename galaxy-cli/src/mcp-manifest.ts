/**
 * Validate a connector.json manifest.
 *
 * Enforces R-SSRF (ssrf.allowed_domains required, no forbidden values) and
 * R-CJS (tsconfig module must be CommonJS when a tsconfig path is provided).
 *
 * Throws with a descriptive message on the first violation found.
 * Returns void on success — suitable for use at generation time.
 */
export function validateConnectorManifest(raw: unknown, opts?: { tsconfigPath?: string }): void {
  if (typeof raw !== "object" || raw === null) {
    throw new Error("connector.json must be a JSON object");
  }

  const manifest = raw as Record<string, unknown>;

  if (!manifest["name"] || typeof manifest["name"] !== "string") {
    throw new Error('connector.json: "name" is required and must be a string');
  }

  if (!manifest["version"] || typeof manifest["version"] !== "string") {
    throw new Error('connector.json: "version" is required and must be a string');
  }

  // R-SSRF: ssrf.allowed_domains is required and must not contain forbidden values
  const ssrf = manifest["ssrf"] as Record<string, unknown> | undefined;
  if (
    !ssrf ||
    !Array.isArray(ssrf["allowed_domains"]) ||
    (ssrf["allowed_domains"] as unknown[]).length === 0
  ) {
    throw new Error(
      "connector.json: ssrf.allowed_domains is required and must be a non-empty array (R-SSRF)"
    );
  }

  const allowedDomains = ssrf["allowed_domains"] as unknown[];
  for (const d of allowedDomains) {
    if (typeof d !== "string") {
      throw new Error(
        `connector.json: ssrf.allowed_domains contains a non-string value: ${JSON.stringify(d)}`
      );
    }
  }

  validateSsrfAllowedDomains(allowedDomains as string[]);

  // R-CJS: if tsconfig path provided, verify "module": "CommonJS"
  if (opts?.tsconfigPath) {
    let tsconfig: unknown;
    try {
      tsconfig = JSON.parse(readFileSync(opts.tsconfigPath, "utf-8"));
    } catch {
      throw new Error(`connector.json (R-CJS): cannot read tsconfig at "${opts.tsconfigPath}"`);
    }
    if (typeof tsconfig !== "object" || tsconfig === null) {
      throw new Error("connector.json (R-CJS): tsconfig must be a JSON object");
    }
    const compilerOptions = (tsconfig as Record<string, unknown>)["compilerOptions"];
    if (typeof compilerOptions !== "object" || compilerOptions === null) {
      throw new Error('connector.json (R-CJS): tsconfig is missing "compilerOptions"');
    }
    const moduleValue = (compilerOptions as Record<string, unknown>)["module"];
    if (typeof moduleValue !== "string" || moduleValue.toLowerCase() !== "commonjs") {
      throw new Error(
        `connector.json (R-CJS): tsconfig.compilerOptions.module must be "CommonJS", got "${String(moduleValue)}"`
      );
    }
  }
}

